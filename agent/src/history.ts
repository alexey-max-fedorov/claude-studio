import type { AttachmentSummary, ChatItem } from "@claude-studio/protocol"
import { assistantBlockToItem, toolResultItems, tsOf } from "./items.js"
import { BROWSER_CONTEXT_MARKER, EMPTY_TEXT_PLACEHOLDER, unescapeAttr, unneutralize } from "./user-message.js"

/*
 * Converts a transcript (getSessionMessages output) into ChatItems with the
 * same ids the live stream uses. Works for panel sessions and terminal
 * sessions alike.
 */

const ATTACHMENT_TYPES = new Set<AttachmentSummary["type"]>(["page", "selection", "page_text", "screenshot", "element"])

function attr(tag: string, name: string): string {
  const m = new RegExp(`\\b${name}="([^"]*)"`).exec(tag)
  return m ? unneutralize(unescapeAttr(m[1])) : ""
}

/** Parse the opening `<browser-context ...>` tag of a text block into a summary. */
export function parseBrowserContext(text: string): AttachmentSummary | null {
  if (!text.startsWith(BROWSER_CONTEXT_MARKER)) return null
  const end = text.indexOf(">")
  const tag = end === -1 ? text : text.slice(0, end + 1)
  const type = attr(tag, "type") as AttachmentSummary["type"]
  const title = attr(tag, "title")
  const url = attr(tag, "url")
  return { type: ATTACHMENT_TYPES.has(type) ? type : "page", label: title || url || type || "browser context" }
}

const ANSI_RE = /\x1b\[[0-9;?]*[A-Za-z]/g
const INTERRUPT_TEXTS = new Set(["[Request interrupted by user]", "[Request interrupted by user for tool use]"])

function tagBody(text: string, tag: string): string | null {
  const m = new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`).exec(text)
  return m ? m[1] : null
}

/**
 * How to show a plain-text user entry that Claude Code itself wrote. Only
 * exact known shapes match, so a user message that merely starts with
 * "Caveat:" or "<system-reminder>" is still shown as typed.
 */
export type InjectedShape =
  | { kind: "skip" }
  | { kind: "user"; text: string }
  | { kind: "system"; text: string }
  | null

export function classifyInjected(raw: string): InjectedShape {
  const t = raw.trim()
  if (t.startsWith("<command-name>") && t.includes("</command-name>")) {
    let name = (tagBody(t, "command-name") ?? "").trim()
    if (name && !name.startsWith("/")) name = `/${name}`
    const args = (tagBody(t, "command-args") ?? "").trim()
    return { kind: "user", text: args ? `${name} ${args}` : name }
  }
  if (t.startsWith("<bash-input>") && t.endsWith("</bash-input>")) {
    return { kind: "user", text: `!${(tagBody(t, "bash-input") ?? "").trim()}` }
  }
  if (/^<(local-command-stdout|local-command-stderr|bash-stdout|bash-stderr)>/.test(t)) {
    const out = ["local-command-stdout", "local-command-stderr", "bash-stdout", "bash-stderr"]
      .map((tag) => tagBody(t, tag))
      .filter((x): x is string => !!x && !!x.trim())
      .join("\n")
      .replace(ANSI_RE, "")
      .trim()
    return out ? { kind: "system", text: out } : { kind: "skip" }
  }
  if (/^<local-command-caveat>[\s\S]*<\/local-command-caveat>$/.test(t)) return { kind: "skip" }
  if (/^<system-reminder>[\s\S]*<\/system-reminder>$/.test(t)) return { kind: "skip" }
  if (/^<task-notification>[\s\S]*<\/task-notification>$/.test(t)) return { kind: "skip" }
  if (t.startsWith("Caveat: The messages below were generated by the user while running local commands")) return { kind: "skip" }
  if (INTERRUPT_TEXTS.has(t)) return { kind: "system", text: "Interrupted by the user." }
  return null
}

/**
 * A user transcript entry to ChatItems. Browser context blocks become
 * attachment summaries; the user's text is the non-marker text (the last
 * block for panel messages, the only one for terminal messages).
 */
export function userEntryToItems(id: string, content: unknown, ts: number): ChatItem[] {
  const blocks: any[] = typeof content === "string" ? [{ type: "text", text: content }] : Array.isArray(content) ? content : []
  const texts: string[] = []
  const attachments: AttachmentSummary[] = []
  let lastWasScreenshotMarker = false
  for (const b of blocks) {
    if (!b || typeof b !== "object") continue
    if (b.type === "text" && typeof b.text === "string") {
      const ctx = parseBrowserContext(b.text)
      if (ctx) {
        attachments.push(ctx)
        lastWasScreenshotMarker = ctx.type === "screenshot"
        continue
      }
      texts.push(b.text)
      lastWasScreenshotMarker = false
    } else if (b.type === "image") {
      // The image right after a screenshot marker belongs to that marker.
      if (!lastWasScreenshotMarker) attachments.push({ type: "screenshot", label: "image" })
      lastWasScreenshotMarker = false
    } else if (b.type === "tool_result") {
      return []
    }
  }
  if (texts.length === 0 && attachments.length === 0) return []
  if (attachments.length === 0 && texts.length === 1) {
    const shape = classifyInjected(texts[0])
    if (shape?.kind === "skip") return []
    if (shape?.kind === "system") return [{ kind: "system", id, text: shape.text, ts }]
    if (shape?.kind === "user") return [{ kind: "user", id, text: shape.text, attachments: [], ts }]
  }
  let text = texts.join("\n")
  // Attachments-only panel message: show it the way the live item did (no text).
  if (attachments.length > 0 && text === EMPTY_TEXT_PLACEHOLDER) text = ""
  return [{ kind: "user", id, text, attachments, ts }]
}

/**
 * @param localOutputs output of local slash commands keyed by the transcript
 *   entry uuid (newer CLIs store it in system entries whose content the SDK
 *   does not return; see transcript-file.ts).
 */
export function sessionMessagesToItems(messages: readonly any[], localOutputs: ReadonlyMap<string, string> = new Map()): ChatItem[] {
  const items: ChatItem[] = []
  const blockCount = new Map<string, number>()
  for (const m of messages) {
    if (!m || typeof m !== "object") continue
    const ts = tsOf(m.timestamp, 0)
    const parent: string | null = m.parent_tool_use_id ?? null
    const content = m.message?.content

    if (m.type === "system") {
      const out = localOutputs.get(String(m.uuid ?? ""))
      if (out) items.push({ kind: "system", id: String(m.uuid ?? ""), text: out, ts })
      continue
    }

    if (m.type === "assistant") {
      const mid = String(m.message?.id ?? m.uuid ?? "msg")
      for (const block of Array.isArray(content) ? content : []) {
        let index = 0
        if (!parent) {
          index = blockCount.get(mid) ?? 0
          blockCount.set(mid, index + 1)
        }
        const item = assistantBlockToItem(block, `${mid}:${index}`, parent, ts)
        if (item) items.push(item)
      }
      continue
    }

    if (m.type !== "user") continue
    const results = toolResultItems(content, ts)
    if (results.length > 0) {
      items.push(...results)
      continue
    }
    if (parent) continue
    if (m.isCompactSummary === true) {
      items.push({ kind: "system", id: String(m.uuid ?? ""), text: "Earlier conversation was compacted.", ts })
      continue
    }
    if (m.is_meta === true || m.isMeta === true) continue
    items.push(...userEntryToItems(String(m.uuid ?? ""), content, ts))
  }
  return items
}

/** Dedupe key shared by disk history and the live buffer. */
export function itemKey(item: ChatItem): string | null {
  switch (item.kind) {
    case "user":
    case "assistant":
    case "thinking":
    case "tool_use":
      return `${item.kind}:${item.id}`
    case "tool_result":
      return `tool_result:${item.toolUseId}`
    default:
      return item.id ? `${item.kind}:${item.id}` : null
  }
}

/** Disk history plus queued input, volatile items, and blocks still streaming. */
export function mergeLiveHistory(
  disk: ChatItem[],
  buffered: readonly ChatItem[],
  inFlight: readonly { id: string; kind: "text" | "thinking"; text: string }[],
  now: number = Date.now(),
  pendingUserIds: ReadonlySet<string> = new Set(),
): ChatItem[] {
  const out = [...disk]
  const byKey = new Map(disk.flatMap((item) => {
    const key = itemKey(item)
    return key ? [[key, item] as const] : []
  }))
  const matches = buffered.map((item) => byKey.get(itemKey(item) ?? ""))
  const matchedSystems = new Set<ChatItem>(matches.filter((item): item is ChatItem => item?.kind === "system"))
  const systemAliases = new Map<ChatItem, ChatItem>()
  const systemText = (text: string) => text.replace(ANSI_RE, "").replace(/<\/?local-command-(stdout|stderr)>/g, "").trim()
  // Older CLIs persist slash output with a different UUID and stripped formatting.
  for (let i = 0; i < buffered.length; i++) {
    const item = buffered[i]
    if (item.kind !== "system" || !item.id || matches[i]) continue
    let from = 0
    let to = disk.length
    for (let j = i - 1; j >= 0; j--) {
      if (matches[j]) { from = disk.indexOf(matches[j]!) + 1; break }
    }
    for (let j = i + 1; j < buffered.length; j++) {
      if (matches[j]) { to = disk.indexOf(matches[j]!); break }
    }
    const match = disk.slice(from, to).find((candidate) =>
      candidate.kind === "system" && !matchedSystems.has(candidate) && systemText(candidate.text) === systemText(item.text),
    )
    if (match?.kind === "system") {
      matches[i] = match
      matchedSystems.add(match)
      systemAliases.set(match, { ...match, id: item.id })
    }
  }
  let lastMatch = -1
  for (let i = 0; i < matches.length; i++) if (matches[i]) lastMatch = i
  const firstMatch = matches.find((item) => item !== undefined)
  let cursor = firstMatch ? out.indexOf(firstMatch) : out.length
  const seen = new Set(byKey.keys())
  for (let i = 0; i < buffered.length; i++) {
    const item = buffered[i]
    const key = itemKey(item)
    const match = matches[i]
    if (match) {
      if (key) seen.add(key)
      cursor = out.indexOf(match) + 1
      continue
    }
    const volatile = item.kind === "result" || item.kind === "error" || item.kind === "system"
    const queued = item.kind === "user" && pendingUserIds.has(item.id)
    // Missing older ordinary items may have been rewritten by slash commands or compaction.
    if (!key || seen.has(key) || (i < lastMatch && !volatile && !queued)) continue
    seen.add(key)
    out.splice(cursor++, 0, item)
  }
  for (const b of inFlight) {
    const kind = b.kind === "text" ? "assistant" : "thinking"
    // Empty blocks (e.g. thinking with its display omitted) never get a final item.
    if (!b.text || seen.has(`${kind}:${b.id}`)) continue
    out.push({ kind, id: b.id, text: b.text, ts: now })
  }
  return out.map((item) => systemAliases.get(item) ?? item)
}
