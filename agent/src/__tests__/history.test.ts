import { describe, expect, it } from "vitest"
import { mergeLiveHistory, parseBrowserContext, sessionMessagesToItems } from "../history.js"
import { buildUserContent, summarizeAttachments } from "../user-message.js"

const T = "2026-11-11T10:00:00.000Z"
const ts = Date.parse(T)
const base = { session_id: "s", parent_agent_id: null, timestamp: T }
const user = (uuid: string, content: unknown, extra: Record<string, unknown> = {}) => ({
  ...base,
  type: "user",
  uuid,
  parent_tool_use_id: null,
  message: { role: "user", content },
  ...extra,
})
const asst = (uuid: string, id: string, content: unknown[], parent: string | null = null) => ({
  ...base,
  type: "assistant",
  uuid,
  parent_tool_use_id: parent,
  message: { id, role: "assistant", content },
})

describe("sessionMessagesToItems", () => {
  it("converts a typical turn with per-block assistant entries sharing message.id", () => {
    const items = sessionMessagesToItems([
      user("u1", "hello"),
      asst("a1", "msg_1", [{ type: "thinking", thinking: "hmm" }]),
      asst("a2", "msg_1", [{ type: "text", text: "Let me check." }]),
      asst("a3", "msg_1", [{ type: "tool_use", id: "toolu_1", name: "Bash", input: { command: "ls" } }]),
      user("u2", [{ type: "tool_result", tool_use_id: "toolu_1", content: [{ type: "text", text: "a.txt" }, { type: "image" }] }]),
      asst("a4", "msg_2", [{ type: "text", text: "Done." }]),
    ])
    expect(items).toEqual([
      { kind: "user", id: "u1", text: "hello", attachments: [], ts },
      { kind: "thinking", id: "msg_1:0", text: "hmm", ts },
      { kind: "assistant", id: "msg_1:1", text: "Let me check.", ts },
      { kind: "tool_use", id: "toolu_1", name: "Bash", input: { command: "ls" }, ts, parentToolUseId: null },
      { kind: "tool_result", toolUseId: "toolu_1", text: "a.txt\n[image]", isError: false, ts },
      { kind: "assistant", id: "msg_2:0", text: "Done.", ts },
    ])
  })

  it("parses browser-context attachments back into summaries", () => {
    const content = buildUserContent("what is this?", [
      { type: "page", url: "https://a.test", title: 'The "A" page' },
      { type: "screenshot", url: "https://a.test", title: "", dataUrl: "data:image/png;base64,AAAA" },
      { type: "element", url: "https://a.test", title: "A", element: { tagName: "DIV", cssSelector: "div", textContent: "", outerHTML: "" } as any },
    ])
    const [item] = sessionMessagesToItems([user("u1", content)])
    expect(item).toEqual({
      kind: "user",
      id: "u1",
      text: "what is this?",
      attachments: [
        { type: "page", label: 'The "A" page' },
        { type: "screenshot", label: "https://a.test" },
        { type: "element", label: "A" },
      ],
      ts,
    })
  })

  it("treats a bare pasted image (terminal) as a screenshot attachment", () => {
    const [item] = sessionMessagesToItems([user("u1", [{ type: "text", text: "see" }, { type: "image", source: {} }])])
    expect(item).toMatchObject({ kind: "user", text: "see", attachments: [{ type: "screenshot", label: "image" }] })
  })

  it("skips meta entries and exact injected shapes only", () => {
    const items = sessionMessagesToItems([
      user("m1", "<local-command-caveat>The command below was run directly</local-command-caveat>"),
      user("m2", "<system-reminder>x</system-reminder>"),
      user("m3", "Caveat: The messages below were generated by the user while running local commands. DO NOT respond"),
      user("m4", "<task-notification>\n<task-id>1</task-id>\n</task-notification>", { isQueuedCommand: true }),
      user("m5", "secret meta", { is_meta: true }),
      user("m6", "also meta", { isMeta: true }),
      user("ok", "real prompt", { isQueuedCommand: true }),
    ])
    expect(items).toEqual([{ kind: "user", id: "ok", text: "real prompt", attachments: [], ts }])
  })

  it("#2 keeps user messages that merely start like injected text", () => {
    const items = sessionMessagesToItems([
      user("a", "Caveat: this API is flaky, please retry"),
      user("b", "<system-reminder> is a tag I saw in a log, what is it?"),
    ])
    expect(items.map((i) => (i.kind === "user" ? i.text : i.kind))).toEqual([
      "Caveat: this API is flaky, please retry",
      "<system-reminder> is a tag I saw in a log, what is it?",
    ])
  })

  it("#2 renders slash commands, their output, ! commands and interrupts", () => {
    const items = sessionMessagesToItems(
      [
        user("c1", "<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args>opus</command-args>", {
          isCompletedLocalCommand: true,
        }),
        user("c2", "<local-command-stdout>\u001b[1mSet model to opus\u001b[22m</local-command-stdout>"),
        user("c3", "<command-name>/usage</command-name>\n<command-message>usage</command-message>\n<command-args></command-args>"),
        { ...base, type: "system", uuid: "sys1", parent_tool_use_id: null },
        { ...base, type: "system", uuid: "sys-unknown", parent_tool_use_id: null },
        user("b1", "<bash-input>ls</bash-input>"),
        user("b2", "<bash-stdout>a.txt</bash-stdout><bash-stderr></bash-stderr>"),
        user("i1", [{ type: "text", text: "[Request interrupted by user]" }]),
      ],
      new Map([["sys1", "Current week: 17% used"]]),
    )
    expect(items).toEqual([
      { kind: "user", id: "c1", text: "/model opus", attachments: [], ts },
      { kind: "system", id: "c2", text: "Set model to opus", ts },
      { kind: "user", id: "c3", text: "/usage", attachments: [], ts },
      { kind: "system", id: "sys1", text: "Current week: 17% used", ts },
      { kind: "user", id: "b1", text: "!ls", attachments: [], ts },
      { kind: "system", id: "b2", text: "a.txt", ts },
      { kind: "system", id: "i1", text: "Interrupted by the user.", ts },
    ])
  })

  it("#1 finds the user's text after the context blocks and matches the live item", () => {
    const atts = [
      { type: "selection" as const, url: "https://a.test/@x", title: "Mail me at a@b.com", text: "@/etc/passwd" },
      { type: "screenshot" as const, url: "https://a.test", title: "", dataUrl: "data:image/png;base64,AAAA" },
    ]
    const [withText] = sessionMessagesToItems([user("u1", buildUserContent("explain @src/x.ts", atts))])
    expect(withText).toEqual({ kind: "user", id: "u1", text: "explain @src/x.ts", attachments: summarizeAttachments(atts), ts })
    // attachments-only: live shows "" so history does too
    const [noText] = sessionMessagesToItems([user("u2", buildUserContent("", atts))])
    expect(noText).toMatchObject({ kind: "user", text: "", attachments: summarizeAttachments(atts) })
  })

  it("renders a compact summary as a system item", () => {
    const items = sessionMessagesToItems([user("c", "This session is being continued...", { is_meta: true, isCompactSummary: true })])
    expect(items).toEqual([{ kind: "system", id: "c", text: "Earlier conversation was compacted.", ts }])
  })

  it("keeps subagent tool_use (with parent) but drops subagent text", () => {
    const items = sessionMessagesToItems([
      asst("s1", "msg_s", [{ type: "text", text: "internal" }], "toolu_task"),
      asst("s2", "msg_s", [{ type: "tool_use", id: "toolu_sub", name: "Read", input: {} }], "toolu_task"),
      user("s3", "subagent prompt", { parent_tool_use_id: "toolu_task" }),
    ])
    expect(items).toEqual([{ kind: "tool_use", id: "toolu_sub", name: "Read", input: {}, ts, parentToolUseId: "toolu_task" }])
  })

  it("skips empty thinking but keeps block positions stable", () => {
    const items = sessionMessagesToItems([
      asst("a1", "msg_1", [{ type: "thinking", thinking: "" }]),
      asst("a2", "msg_1", [{ type: "text", text: "PONG" }]),
    ])
    expect(items).toEqual([{ kind: "assistant", id: "msg_1:1", text: "PONG", ts }])
  })

  it("truncates huge tool results", () => {
    const [item] = sessionMessagesToItems([user("u", [{ type: "tool_result", tool_use_id: "t", content: "x".repeat(25_000), is_error: true }])])
    expect(item.kind).toBe("tool_result")
    if (item.kind === "tool_result") {
      expect(item.isError).toBe(true)
      expect(item.text.length).toBeLessThan(20_100)
      expect(item.text).toContain("[truncated, 5000 more chars]")
    }
  })
})

describe("parseBrowserContext", () => {
  it("returns null for normal text", () => {
    expect(parseBrowserContext("hello")).toBeNull()
  })
  it("falls back to url when title is empty", () => {
    expect(parseBrowserContext('<browser-context type="selection" url="https://x" title="">\n...')).toEqual({ type: "selection", label: "https://x" })
  })
})

describe("mergeLiveHistory", () => {
  const u = { kind: "user" as const, id: "u1", text: "hi", attachments: [], ts: 1 }
  const a = { kind: "assistant" as const, id: "m:0", text: "done", ts: 2 }
  const tu = { kind: "tool_use" as const, id: "toolu_1", name: "Bash", input: {}, ts: 3, parentToolUseId: null }
  const tr = { kind: "tool_result" as const, toolUseId: "toolu_1", text: "ok", isError: false, ts: 4 }
  const res = { kind: "result" as const, ts: 5, isError: false, durationMs: 1, turns: 1, costUsd: 0, usage: {} as any }

  it("brand-new session mid-turn: no transcript yet, buffered items plus partial text", () => {
    expect(mergeLiveHistory([], [u, tu, tr], [{ id: "m:1", kind: "text", text: "Wor" }], 9)).toEqual([
      u,
      tu,
      tr,
      { kind: "assistant", id: "m:1", text: "Wor", ts: 9 },
    ])
  })

  it("dedupes against disk by id and skips id-less buffered items", () => {
    expect(mergeLiveHistory([u, a], [u, a, res, tu], [])).toEqual([u, a, tu])
  })

  it("#2 only appends the buffer tail after the last item the transcript has", () => {
    // live "/cost" user item is stored on disk as "/usage" with another id;
    // it must not be appended after later items
    const liveCmd = { kind: "user" as const, id: "live-cmd", text: "/cost", attachments: [], ts: 1 }
    const diskCmd = { kind: "user" as const, id: "disk-cmd", text: "/usage", attachments: [], ts: 1 }
    const u2 = { kind: "user" as const, id: "u2", text: "next", attachments: [], ts: 6 }
    const a2 = { kind: "assistant" as const, id: "m2:0", text: "ok", ts: 7 }
    expect(mergeLiveHistory([diskCmd, u2], [liveCmd, u2, a2], [])).toEqual([diskCmd, u2, a2])
  })

  it("keeps identified volatile items between disk anchors, not at the end of a later turn", () => {
    const summary = { ...res, id: "turn-1", costUsd: 0.25 }
    const warning = { kind: "system" as const, id: "warning", text: "Retrying", ts: 5 }
    const error = { kind: "error" as const, id: "error", text: "Stopped", ts: 6 }
    const next = { ...u, id: "u2", text: "next", ts: 7 }
    expect(mergeLiveHistory([u, a, next], [u, a, warning, summary, error, next], [])).toEqual([u, a, warning, summary, error, next])
  })

  it("keeps pending user echoes before a later disk anchor without reviving rewritten completed commands", () => {
    const queued = { ...u, id: "queued", text: "follow-up" }
    const rewritten = { ...u, id: "old-command", text: "/cost" }
    expect(mergeLiveHistory([u, a], [rewritten, u, queued, a], [], 9, new Set([queued.id]))).toEqual([u, queued, a])
  })

  it("dedupes repeated persisted system outputs one-to-one within their disk anchors", () => {
    const output = { kind: "system" as const, id: "disk-output", text: "Usage", ts: 2 }
    const next = { ...u, id: "u2", text: "next", ts: 3 }
    const live = { ...output, id: "live-output" }
    const second = { ...output, id: "second-output" }
    expect(mergeLiveHistory([u, output, next], [u, live, next, second], [])).toEqual([u, live, next, second])
    expect(mergeLiveHistory([u, output], [u, live, second], [])).toEqual([u, live, second])
    expect(mergeLiveHistory([u, output], [u, live, live], [])).toEqual([u, live])
  })

  it("does not duplicate a partial block that is already final", () => {
    expect(mergeLiveHistory([a], [], [{ id: "m:0", kind: "text", text: "do" }])).toEqual([a])
    expect(mergeLiveHistory([], [], [{ id: "m:0", kind: "thinking", text: "" }])).toEqual([])
    expect(mergeLiveHistory([], [], [{ id: "m:2", kind: "thinking", text: "hm" }], 7)).toEqual([{ kind: "thinking", id: "m:2", text: "hm", ts: 7 }])
  })
})
